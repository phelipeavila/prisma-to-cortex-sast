def cmd_all(args) -> None:
    """Run fetch -> sarif -> upload with the same options."""
    if not args.dry_run:
        # Fail fast on missing collector settings before the long Prisma fetch.
        load_collector_config(args)
    logger.info("=== Stage 1/3: fetch ===")
    cmd_fetch(args)
    logger.info("=== Stage 2/3: sarif ===")
    cmd_sarif(args)
    logger.info("=== Stage 3/3: upload ===")
    cmd_upload(args)


