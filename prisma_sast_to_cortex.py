PRISMA_SETTINGS = ("PRISMA_API_URL", "PRISMA_ACCESS_KEY_ID", "PRISMA_SECRET_KEY")
COLLECTOR_SETTINGS = (
    "CORTEX_COLLECTOR_URL", "CORTEX_COLLECTOR_TOKEN_ID", "CORTEX_COLLECTOR_TOKEN",
)
CORTEX_API_SETTINGS = ("CORTEX_API_URL", "CORTEX_API_KEY_ID", "CORTEX_API_KEY")
ALL_SETTINGS = PRISMA_SETTINGS + COLLECTOR_SETTINGS + CORTEX_API_SETTINGS
DEFAULT_REPO_MAP_FILE = BASE_DIR / "repo_map.csv"
DEFAULT_OUTPUT_DIR = BASE_DIR / "output"

PAGE_LIMIT = 1000
MAX_RETRIES = 5
HTTP_TIMEOUT = 120

# Prisma check statuses to export: open findings and suppressed findings.
STATUSES = {"open": "Error", "suppressed": "Suppressed"}

# SARIF settings
SARIF_SCHEMA = "https://json.schemastore.org/sarif-2.1.0.json"
DEFAULT_TOOL_NAME = "PrismaCloudSAST"
MAX_SARIF_BYTES = 10 * 1024 * 1024  # Cortex collector upload limit per request
