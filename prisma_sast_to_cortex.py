class PrismaClient:
    """Minimal Prisma Cloud API client with token refresh and retries."""

    def __init__(self, api_url: str, key_id: str, secret_key: str):
        self.api_url = api_url.rstrip("/")
        self.key_id = key_id
        self.secret_key = secret_key
        self.token = None

    @classmethod
    def from_settings(cls, settings: dict, env_file: Path) -> "PrismaClient":
        require_settings(settings, PRISMA_SETTINGS, "Prisma Cloud (fetch)", env_file)
        return cls(
            settings["PRISMA_API_URL"],
            settings["PRISMA_ACCESS_KEY_ID"],
            settings["PRISMA_SECRET_KEY"],
        )

    def login(self) -> None:
        logger.debug("Authenticating against %s", self.api_url)
        data = self._raw_request(
            "POST",
            "login",
            body={"username": self.key_id, "password": self.secret_key},
            auth=False,
        )
        self.token = data.get("token")
        if not self.token:
            raise SystemExit("Prisma login did not return a token")
        logger.info("Authenticated to Prisma Cloud")

    def request(self, method: str, endpoint: str, body=None):
        """Send an authenticated request, re-authenticating once on 401."""
        if not self.token:
            self.login()
        try:
            return self._raw_request(method, endpoint, body=body)
        except urllib.error.HTTPError as err:
            if err.code != 401:
                raise
            logger.info("Token expired, re-authenticating")
            self.login()
            return self._raw_request(method, endpoint, body=body)

    def _raw_request(self, method: str, endpoint: str, body=None, auth=True):
        url = f"{self.api_url}/{endpoint.lstrip('/')}"
        payload = json.dumps(body).encode() if body is not None else None
        headers = {"Content-Type": "application/json", "Accept": "application/json"}
        if auth:
            headers["x-redlock-auth"] = self.token

        for attempt in range(1, MAX_RETRIES + 1):
            req = urllib.request.Request(url, data=payload, headers=headers, method=method)
            try:
                with urllib.request.urlopen(req, timeout=HTTP_TIMEOUT) as resp:
                    text = resp.read().decode() or "null"
                    return json.loads(text)
            except urllib.error.HTTPError as err:
                retryable = err.code == 429 or err.code >= 500
                if not retryable or attempt == MAX_RETRIES:
                    detail = err.read().decode(errors="replace")[:500]
                    logger.error("%s %s -> HTTP %s: %s", method, url, err.code, detail)
                    raise
            except urllib.error.URLError as err:
                if attempt == MAX_RETRIES:
                    raise
                logger.warning("Network error on %s: %s", url, err.reason)
            wait = 2 ** attempt
            logger.warning("Retrying %s %s in %ss (attempt %s)", method, url, wait, attempt)
            time.sleep(wait)

    # -- API calls ---------------------------------------------------------

    def list_repositories(self) -> list[dict]:
        data = self.request("GET", "code/api/v1/repositories")
        if isinstance(data, dict):
            # Defensive: some tenants wrap the list in a "data" key.
            data = data.get("data", data.get("repositories", []))
        return data or []

    def get_weaknesses(self, repo_id: str, check_status: str) -> list[dict]:
        """Return all SAST weaknesses for a repo/status, paginating until empty."""
        issues = []
        offset = 0
        while True:
            payload = {
                "filters": {
                    "repositories": [repo_id],
                    "branch": "default",
                    "checkStatus": check_status,
                    "codeCategories": ["Weaknesses"],
                },
                "limit": PAGE_LIMIT,
                "offset": offset,
            }
            data = self.request("POST", "code/api/v2/code-issues/branch_scan", body=payload)
            data = data or {}
            page = data.get("data", [])
            issues.extend(page)
            logger.debug("  %s offset=%s -> %s issues", check_status, offset, len(page))
            # Prefer the API's "hasNext" flag; fall back to a short-page check.
            has_next = data.get("hasNext", len(page) == PAGE_LIMIT)
            if not page or not has_next:
                break
            offset += PAGE_LIMIT
        return issues


