def load_settings(path: Path) -> dict[str, str]:
    """
    Load the script settings: values from the .env file, overridden by
    environment variables with the same name (handy for CI/CD secrets).
    A missing .env file is fine when everything comes from the environment.
    """
    settings = load_env_file(path) if path.exists() else {}
    for key in ALL_SETTINGS:
        if os.environ.get(key):
            settings[key] = os.environ[key]
    return settings


def require_settings(settings: dict, keys: tuple, purpose: str, env_file: Path) -> None:
    """Exit with a clear message when required settings are missing."""
    missing = [k for k in keys if not settings.get(k)]
    if missing:
        raise SystemExit(
            f"Missing settings for {purpose}: {', '.join(missing)}. "
            f"Set them in {env_file} or as environment variables (see README.md)."
        )
    for key in keys:
        if key.endswith("_URL"):
            problem = url_problem(settings[key])
            if problem:
                # Never print the value itself: a misplaced secret may be in it.
                raise SystemExit(f"Invalid {key} in {env_file}: {problem}.")


def url_problem(url: str) -> str | None:
    """Return a description of what is wrong with an API URL, or None if it looks valid."""
    parsed = urllib.parse.urlparse(url.strip())
    if parsed.scheme != "https":
        return "it must start with https://"
    host = parsed.hostname or ""
    if not host or " " in url.strip():
        return "the host name is missing or contains spaces"
    labels = host.split(".")
    if any(len(label) > 63 or not label for label in labels) or "." not in host:
        return (
            "the host name is malformed (check that an API key or token was not "
            "pasted into the URL, and that each variable is on its own line)"
        )
    return None


def load_env_file(path: Path) -> dict[str, str]:
    """Parse a simple KEY=VALUE .env file (comments and quotes supported)."""
    values = {}
    for raw_line in path.read_text().splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        if line.startswith("export "):
            line = line[len("export "):]
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip().strip('"').strip("'")
    return values


def safe_name(value: str) -> str:
    """Turn a repository full name into a filesystem-friendly name."""
    return re.sub(r"[^A-Za-z0-9._-]+", "__", value).strip("_")


def repo_full_name(repo: dict) -> str:
    """Return 'owner/repository' for a Prisma repository object."""
    owner = repo.get("owner") or ""
    name = repo.get("repository") or repo.get("name") or repo.get("id")
    return f"{owner}/{name}" if owner else str(name)


def write_json(path: Path, data) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False))


