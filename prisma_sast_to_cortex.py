def load_collector_config(args) -> dict:
    """
    Resolve the collector credentials from the settings.

    CORTEX_COLLECTOR_URL      -> upload URL ('Copy API URL' in the console)
    CORTEX_COLLECTOR_TOKEN_ID -> Token ID ('x-crtx-auth-id' header)
    CORTEX_COLLECTOR_TOKEN    -> API Token ('Authorization' header)
    """
    require_settings(
        args.settings,
        COLLECTOR_SETTINGS,
        "the Cortex collector (upload). Create the 3rd Party AppSec Collector "
        "in the Cortex console first, then provide",
        Path(args.env_file),
    )
    config = {
        "url": args.settings["CORTEX_COLLECTOR_URL"],
        "id": args.settings["CORTEX_COLLECTOR_TOKEN_ID"],
        "token": args.settings["CORTEX_COLLECTOR_TOKEN"],
    }
    if "/collectors/" not in config["url"]:
        logger.warning("Collector URL does not look like .../collectors/<id>: %s", config["url"])
    return config


REPO_MAP_FIELDS = ["prisma_repository", "repository_url", "repository_id"]


def load_repo_map(path: Path) -> dict[str, dict]:
    """
    Load the optional manual mapping CSV.

    Columns: prisma_repository, repository_url, repository_id. Fill either
    repository_url or repository_id (the Cortex repository asset id, useful
    for Cortex repositories that have no URL, e.g. GitHub Actions/Jenkins).
    """
    if not path.exists():
        return {}
    mapping = {}
    with path.open(newline="", encoding="utf-8-sig") as handle:
        for row in csv.DictReader(handle):
            name = (row.get("prisma_repository") or "").strip()
            target = {}
            if (row.get("repository_id") or "").strip():
                target["repository_id"] = row["repository_id"].strip()
            if (row.get("repository_url") or "").strip():
                target["repository_url"] = row["repository_url"].strip()
            if name and target:
                mapping[name.lower()] = target
    logger.info("Loaded %s repository mapping(s) from %s", len(mapping), path)
    return mapping


def resolve_target(sarif: dict, repo_map: dict[str, dict]) -> dict:
    """
    Return the Cortex repository query params for a SARIF file:
    {'repository_id': ...} and/or {'repository_url': ...}; empty if unknown.
    The manual mapping wins over the Prisma repository URL.
    """
    run = sarif["runs"][0]
    name = run.get("properties", {}).get("prismaRepository", "")
    if name.lower() in repo_map:
        return dict(repo_map[name.lower()])
    provenance = run.get("versionControlProvenance") or [{}]
    url = provenance[0].get("repositoryUri")
    return {"repository_url": url} if url else {}


def normalize_url(url: str | None) -> str:
    return (url or "").strip().lower().rstrip("/").removesuffix(".git")


def strip_tenant_prefix(name: str) -> str:
    """'<prisma tenant id>_owner/repo' (Prisma CLI repos) -> 'owner/repo'."""
    return re.sub(r"^\d+_", "", name)


class CortexRepoIndex:
    """Repositories onboarded in Cortex Cloud, indexed for the pre-check."""

    def __init__(self, repos: list[dict]):
        self.repos = repos
        self.by_id = {r["id"]: r for r in repos if r.get("id")}
        self.by_url = {normalize_url(r.get("url")): r for r in repos if r.get("url")}
        self.by_owner_name: dict[tuple, list[dict]] = {}
        for repo in repos:
            key = ((repo.get("owner") or "").lower(), (repo.get("name") or "").lower())
            self.by_owner_name.setdefault(key, []).append(repo)

    @classmethod
    def from_settings(cls, settings: dict, env_file: Path) -> "CortexRepoIndex":
        """List Cortex repositories with the tenant API key (CORTEX_API_*)."""
        require_settings(settings, CORTEX_API_SETTINGS, "--precheck", env_file)
        url = settings["CORTEX_API_URL"].rstrip("/") + "/public_api/appsec/v1/repositories"
        headers = {
            "Authorization": settings["CORTEX_API_KEY"],
            "x-xdr-auth-id": settings["CORTEX_API_KEY_ID"],
            "Accept": "application/json",
        }
        req = urllib.request.Request(url, headers=headers)
        try:
            with urllib.request.urlopen(req, timeout=HTTP_TIMEOUT) as resp:
                data = json.loads(resp.read() or b"[]")
        except urllib.error.HTTPError as err:
            detail = err.read().decode(errors="replace")[:300]
            raise SystemExit(
                f"Pre-check failed listing Cortex repositories (HTTP {err.code}): {detail}"
            )
        if isinstance(data, dict):
            data = data.get("data", data.get("repositories", []))
        logger.info("Pre-check: %s repositories onboarded in Cortex", len(data))
        return cls(data)

    def find(self, target: dict) -> dict | None:
        """Exact match by repository_id or normalized repository_url."""
        if target.get("repository_id") in self.by_id:
            return self.by_id[target["repository_id"]]
        return self.by_url.get(normalize_url(target.get("repository_url")))

    def suggest(self, prisma_name: str) -> list[dict]:
        """Candidate matches by owner/name (Prisma tenant prefix removed)."""
        parts = strip_tenant_prefix(prisma_name).lower().split("/")
        if len(parts) < 2:
            return []
        name = parts[-1]
        # Prisma names may carry extra segments (e.g. Azure org/project/repo).
        owners = {parts[0], parts[-2]}
        found = []
        for owner in owners:
            found.extend(self.by_owner_name.get((owner, name), []))
        return list({r["id"]: r for r in found}.values())


def upload_sarif(config: dict, target: dict, body: bytes) -> tuple[int, dict]:
    """POST a SARIF document to the collector. Returns (http_status, response_json)."""
    query = urllib.parse.urlencode(target)
    url = f"{config['url']}{'&' if '?' in config['url'] else '?'}{query}"
    headers = {
        "Authorization": config["token"],
        "x-crtx-auth-id": str(config["id"]),
        "Content-Type": "application/json",
        "Accept": "application/json",
    }
    for attempt in range(1, MAX_RETRIES + 1):
        req = urllib.request.Request(url, data=body, headers=headers, method="POST")
        try:
            with urllib.request.urlopen(req, timeout=HTTP_TIMEOUT) as resp:
                text = resp.read().decode(errors="replace")
                return resp.status, _parse_json(text)
        except urllib.error.HTTPError as err:
            text = err.read().decode(errors="replace")
            # 503 means the collector is disabled: retrying will not help.
            retryable = err.code == 429 or (err.code >= 500 and err.code != 503)
            if not retryable or attempt == MAX_RETRIES:
                return err.code, _parse_json(text)
        except urllib.error.URLError as err:
            if attempt == MAX_RETRIES:
                return 0, {"message": f"network error: {err.reason}"}
        wait = 2 ** attempt
        logger.warning("Retrying upload in %ss (attempt %s)", wait, attempt)
        time.sleep(wait)
    return 0, {"message": "upload failed"}


def _parse_json(text: str) -> dict:
    try:
        data = json.loads(text) if text else {}
        return data if isinstance(data, dict) else {"response": data}
    except json.JSONDecodeError:
        return {"message": text[:500]}


def response_message(data: dict) -> str:
    """Extract a readable message from the various Cortex response shapes."""
    reply = data.get("reply") if isinstance(data.get("reply"), dict) else {}
    parts = [
        data.get("status"),
        data.get("errorCode") or reply.get("err_code"),
        data.get("message") or reply.get("err_msg"),
        reply.get("err_extra"),
    ]
    text = " | ".join(str(p) for p in parts if p) or json.dumps(data)[:500]
    return " ".join(text.split())  # flatten newlines for logs and CSV


SUMMARY_FIELDS = [
    "repository", "file", "results", "repository_url", "repository_id",
    "http_status", "status", "message",
]


def write_csv(path: Path, fields: list[str], rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)


def cmd_upload(args) -> None:
    output_dir = Path(args.output_dir)
    sarif_dir = output_dir / "sarif"
    sarif_files = sorted(sarif_dir.glob("*.sarif"))
    if not sarif_files:
        raise SystemExit(f"No SARIF files found in {sarif_dir}. Run 'sarif' first.")

    if args.dry_run:
        logger.info("Dry-run mode (default): nothing will be uploaded. Use --no-dry-run to upload.")
    config = None if args.dry_run else load_collector_config(args)
    repo_map = load_repo_map(Path(args.repo_map))
    index = (
        CortexRepoIndex.from_settings(args.settings, Path(args.env_file))
        if args.precheck
        else None
    )
    wanted = {r.lower() for r in args.repo} if args.repo else None

    rows = []
    unmapped = []  # no target at all -> repo_map_missing.csv
    suggestions = []  # pre-check owner/name candidates -> repo_map_suggested.csv
    for sarif_file in sarif_files:
        body = sarif_file.read_bytes()
        sarif = json.loads(body)
        run = sarif["runs"][0]
        name = run.get("properties", {}).get("prismaRepository", sarif_file.stem)
        if wanted and name.lower() not in wanted:
            continue

        row = {field: "" for field in SUMMARY_FIELDS}
        row.update(repository=name, file=sarif_file.name, results=len(run.get("results", [])))
        target = resolve_target(sarif, repo_map)
        row.update(
            repository_url=target.get("repository_url", ""),
            repository_id=target.get("repository_id", ""),
        )

        if index is not None:
            match = index.find(target) if target else None
            if match:
                # Send the id Cortex knows, so URL case/.git differences do not matter.
                target = {"repository_id": match["id"]}
                row["repository_id"] = match["id"]
            else:
                candidates = index.suggest(name)
                for cand in candidates:
                    suggestions.append({
                        "prisma_repository": name,
                        "repository_url": cand.get("url") or "",
                        "repository_id": cand["id"],
                        "cortex_owner": cand.get("owner"),
                        "cortex_name": cand.get("name"),
                        "cortex_source": cand.get("source"),
                    })
                hint = f"; {len(candidates)} candidate(s) in repo_map_suggested.csv" if candidates else ""
                row.update(status="NOT_ONBOARDED", message=f"repository not found in Cortex{hint}")
                logger.warning("%s: not onboarded in Cortex%s", name, hint)
                rows.append(row)
                continue
        elif not target:
            row.update(status="SKIPPED", message="no repository URL (add it to the repo map)")
            unmapped.append(name)
            logger.warning("%s: skipped, no repository URL", name)
            rows.append(row)
            continue

        target_text = ", ".join(f"{k}={v}" for k, v in target.items())
        if args.dry_run:
            row.update(status="DRY_RUN", message=f"{len(body)} bytes")
            logger.info("%s: [dry-run] would upload %s results (%s bytes) with %s",
                        name, row["results"], len(body), target_text)
            rows.append(row)
            continue

        status, data = upload_sarif(config, target, body)
        message = response_message(data)
        ok = 200 <= status < 300
        row.update(
            http_status=status,
            status=data.get("status") or ("OK" if ok else "FAILED"),
            message=message,
        )
        log = logger.info if ok else logger.error
        log("%s: HTTP %s %s", name, status, message)
        rows.append(row)

    summary_file = output_dir / "summary.csv"
    write_csv(summary_file, SUMMARY_FIELDS, rows)

    if unmapped:
        template = output_dir / "repo_map_missing.csv"
        write_csv(template, REPO_MAP_FIELDS, [{"prisma_repository": n} for n in unmapped])
        logger.info(
            "%s repositories without URL listed in %s; fill repository_url or "
            "repository_id and save it as %s to include them",
            len(unmapped), template, args.repo_map,
        )
    if suggestions:
        suggested = output_dir / "repo_map_suggested.csv"
        fields = REPO_MAP_FIELDS + ["cortex_owner", "cortex_name", "cortex_source"]
        write_csv(suggested, fields, suggestions)
        logger.info(
            "%s owner/name candidate(s) written to %s; review them and copy the "
            "correct rows to %s", len(suggestions), suggested, args.repo_map,
        )

    by_status: dict[str, int] = {}
    for row in rows:
        by_status[row["status"]] = by_status.get(row["status"], 0) + 1
    logger.info("Done: %s", ", ".join(f"{k}={v}" for k, v in sorted(by_status.items())))
    logger.info("Summary written to %s", summary_file)


