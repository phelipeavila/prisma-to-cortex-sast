POLICY_DOCS_FOLDER = {"typescript": "javascript"}

# Prisma severity -> SARIF level and numeric "security-severity" (CVSS-like).
SEVERITY_MAP = {
    "CRITICAL": ("error", "9.5"),
    "HIGH": ("error", "8.0"),
    "MEDIUM": ("warning", "5.5"),
    "LOW": ("note", "3.0"),
    "INFO": ("note", "0.0"),
}

