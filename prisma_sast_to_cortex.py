def build_parser() -> argparse.ArgumentParser:
    # Option groups shared between the default (full) run and the subcommands.
    repo_opts = argparse.ArgumentParser(add_help=False)
    repo_opts.add_argument(
        "--repo",
        action="append",
        metavar="OWNER/NAME",
        help="limit to this Prisma repository (repeatable)",
    )

    sarif_opts = argparse.ArgumentParser(add_help=False)
    sarif_opts.add_argument(
        "--tool-name",
        default=DEFAULT_TOOL_NAME,
        help="SARIF tool.driver.name; must match the Cortex collector name "
        f"(default: {DEFAULT_TOOL_NAME})",
    )

    upload_opts = argparse.ArgumentParser(add_help=False)
    upload_opts.add_argument(
        "--dry-run",
        action=argparse.BooleanOptionalAction,
        default=True,
        help="dry-run is the default: nothing is sent to Cortex. "
        "Use --no-dry-run to actually upload.",
    )
    upload_opts.add_argument(
        "--repo-map",
        default=str(DEFAULT_REPO_MAP_FILE),
        help="optional CSV (prisma_repository,repository_url,repository_id) to "
        "map Prisma repositories to Cortex ones (default: repo_map.csv)",
    )
    upload_opts.add_argument(
        "--precheck",
        action="store_true",
        help="list Cortex repositories first (needs CORTEX_API_* settings) and "
        "skip repositories that are not onboarded",
    )

    def global_opts(suppress_defaults: bool) -> argparse.ArgumentParser:
        """
        Options accepted before or after the subcommand. Subcommands use
        SUPPRESS defaults so they do not overwrite values given earlier.
        """
        def default(value):
            return argparse.SUPPRESS if suppress_defaults else value

        opts = argparse.ArgumentParser(add_help=False)
        opts.add_argument(
            "--env-file",
            default=default(str(DEFAULT_ENV_FILE)),
            help="settings file (default: .env next to the script)",
        )
        opts.add_argument(
            "--output-dir",
            default=default(str(DEFAULT_OUTPUT_DIR)),
            help="output directory (default: output)",
        )
        opts.add_argument(
            "-v", "--verbose", action="store_true", default=default(False),
            help="debug logging",
        )
        return opts

    # Without a subcommand the full pipeline runs, so the top-level parser
    # accepts every stage option.
    parser = argparse.ArgumentParser(
        description=__doc__.split("\n\n")[0]
        + " Without a subcommand, runs fetch -> sarif -> upload.",
        parents=[global_opts(False), repo_opts, sarif_opts, upload_opts],
    )
    parser.set_defaults(func=cmd_all)

    # Subcommands run a single stage. Put their options after the subcommand.
    sub_globals = global_opts(True)
    sub = parser.add_subparsers(dest="command", required=False)
    sub.add_parser(
        "fetch", parents=[sub_globals, repo_opts],
        help="stage 1: download SAST weaknesses from Prisma Cloud",
    ).set_defaults(func=cmd_fetch)
    sub.add_parser(
        "sarif", parents=[sub_globals, repo_opts, sarif_opts],
        help="stage 2: convert raw data into SARIF",
    ).set_defaults(func=cmd_sarif)
    sub.add_parser(
        "upload", parents=[sub_globals, repo_opts, upload_opts],
        help="stage 3: upload SARIF files to an existing Cortex collector",
    ).set_defaults(func=cmd_upload)
    return parser


def main() -> None:
    args = build_parser().parse_args()
    logging.basicConfig(
        level=logging.DEBUG if args.verbose else logging.INFO,
        format="%(asctime)s %(levelname)-7s %(message)s",
        datefmt="%H:%M:%S",
    )
    env_file = Path(args.env_file)
    if not env_file.exists():
        logger.warning("Settings file %s not found; using environment variables only", env_file)
    args.settings = load_settings(env_file)
    try:
        args.func(args)
    except urllib.error.HTTPError as err:
        sys.exit(f"HTTP error {err.code}: {err.reason}")


if __name__ == "__main__":
    main()
