def cmd_fetch(args) -> None:
    raw_dir = Path(args.output_dir) / "raw"
    client = PrismaClient.from_settings(args.settings, Path(args.env_file))

    repos = client.list_repositories()
    logger.info("Found %s repositories in Prisma Cloud", len(repos))
    write_json(raw_dir / "repositories.json", repos)

    if args.repo:
        wanted = {r.lower() for r in args.repo}
        repos = [r for r in repos if repo_full_name(r).lower() in wanted]
        found = {repo_full_name(r).lower() for r in repos}
        for name in sorted(wanted - found):
            logger.warning("Repository not found in Prisma: %s", name)

    totals = {"repos": 0, "repos_with_findings": 0, "open": 0, "suppressed": 0}
    current_files: set[str] = set()
    for repo in repos:
        full_name = repo_full_name(repo)
        logger.info("Fetching weaknesses for %s", full_name)
        result = {"repo": repo}
        for key, status in STATUSES.items():
            result[key] = client.get_weaknesses(repo["id"], status)
            totals[key] += len(result[key])
        totals["repos"] += 1
        n_open, n_supp = len(result["open"]), len(result["suppressed"])
        logger.info("  %s: %s open, %s suppressed", full_name, n_open, n_supp)
        raw_file = raw_dir / f"{safe_name(full_name)}.json"
        if n_open or n_supp:
            totals["repos_with_findings"] += 1
            write_json(raw_file, result)
            current_files.add(raw_file.name)
        elif raw_file.exists():
            raw_file.unlink()  # drop stale data from a previous run

    if not args.repo:
        # Full run: remove raw files of repositories no longer present/affected.
        for stale in raw_dir.glob("*.json"):
            if stale.name != "repositories.json" and stale.name not in current_files:
                logger.debug("Removing stale raw file %s", stale.name)
                stale.unlink()

    logger.info(
        "Done: %(repos)s repos processed, %(repos_with_findings)s with findings, "
        "%(open)s open, %(suppressed)s suppressed",
        totals,
    )
    logger.info("Raw data written to %s", raw_dir)


