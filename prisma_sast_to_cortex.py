#!/usr/bin/env python3
"""
Migrate Prisma Cloud SAST findings (Code Weaknesses) to Cortex Cloud.

Overview
--------
For every repository known to Prisma Cloud Application Security, this script
collects all SAST weaknesses on the default branch (open and suppressed),
converts them into one SARIF 2.1.0 file per repository and uploads each file
to Cortex Cloud through the "3rd Party AppSec Collector" data source.

Pipeline
--------
Without a subcommand the full pipeline runs: fetch -> sarif -> upload.
Each stage can also be run on its own (options go after the subcommand):

    fetch     Prisma Cloud API -> output/raw/<owner>__<repo>.json
              (plus output/raw/repositories.json)
    sarif     output/raw/*.json -> output/sarif/<owner>__<repo>.sarif
              Offline. Files above 10 MB are split into .partN.sarif.
    upload    output/sarif/*.sarif -> Cortex collector endpoint
              Writes output/summary.csv with one row per repository.

Safety
------
Upload runs in DRY-RUN mode by default: nothing is sent to Cortex unless
--no-dry-run is given.

Configuration
-------------
All settings live in a single .env file next to this script (another file
can be given with --env-file). Environment variables with the same names
override the file, which is handy for CI/CD secrets.

    Prisma Cloud (source), required by 'fetch':
        PRISMA_API_URL             Prisma Cloud API URL
        PRISMA_ACCESS_KEY_ID       access key id
        PRISMA_SECRET_KEY          secret key

    Cortex collector (destination), required by 'upload --no-dry-run'.
    Generated by the 3rd Party AppSec Collector, which must be created
    beforehand in the Cortex console:
        CORTEX_COLLECTOR_URL       collector API URL (.../collectors/<id>)
        CORTEX_COLLECTOR_TOKEN_ID  collector Token ID
        CORTEX_COLLECTOR_TOKEN     collector API Token

    Cortex tenant API key, optional, only used by --precheck:
        CORTEX_API_URL             tenant API URL (https://api-<tenant>...)
        CORTEX_API_KEY_ID          API key id
        CORTEX_API_KEY             API key

repo_map.csv (optional) maps Prisma repositories to Cortex repositories:
    prisma_repository, repository_url, repository_id

Repository matching
-------------------
Cortex only accepts findings for repositories already onboarded in Cortex.
The target repository is taken from repo_map.csv when listed there,
otherwise from the repository URL reported by Prisma. With --precheck the
script lists Cortex repositories first, skips the ones not onboarded
(NOT_ONBOARDED) and writes owner/name candidates to
output/repo_map_suggested.csv for manual review.

Examples
--------
    python3 prisma_sast_to_cortex.py                          # dry-run
    python3 prisma_sast_to_cortex.py --precheck --no-dry-run  # real upload
    python3 prisma_sast_to_cortex.py --repo owner/name --no-dry-run
    python3 prisma_sast_to_cortex.py upload --precheck

Requirements: Python 3.10+, standard library only. See README.md.
"""

